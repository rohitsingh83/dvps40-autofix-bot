def _build_pr_body(
    error: log_parser.ParsedError,
    patch: agent.AgentPatch,
    review: agent.ReviewResult,
) -> str:
    steps_md = "\n".join(f"{i}. {s}" for i, s in enumerate(patch.steps, 1))
    return f"""## 🤖 Autonomous AutoFix — {error.platform.value.title()}

> This PR was automatically generated by the DVPS40 DevOps Telegram Bot.
> **Review carefully before merging.**

---

### Incident Summary

| Field | Value |
|---|---|
| Platform | `{error.platform.value}` |
| Project | `{error.project_name}` |
| Environment | `{error.environment}` |
| Error Type | `{error.error_type or "Unknown"}` |
| Deployment ID | `{error.deployment_id}` |

### Root Cause

{patch.root_cause}

### Step-by-Step Analysis

{steps_md}

### Explanation of Fix

{patch.explanation}

### Self-Code-Review Result

✅ **Approved by automated reviewer**

### Diff

```diff
--- a/{patch.file_path}
+++ b/{patch.file_path}
{chr(10).join('- ' + line for line in patch.original_snippet.splitlines())}
{chr(10).join('+ ' + line for line in patch.fixed_snippet.splitlines())}
```

---
*Base branch: `{settings.dev_branch}` | Auto-generated by DVPS40 Telegram Bot*
"""


async def run_autofix_pipeline_from_logs(raw_logs: str, platform_str: str = "railway", project: str = "telegram-service") -> dict:
    """Executes the full DVPS40 8-stage pipeline from raw logs."""
    deployment_id = f"tg_{int(time.time())}"
    platform_enum = (
        log_parser.Platform.VERCEL
        if platform_str.lower() == "vercel"
        else log_parser.Platform.RAILWAY
    )

    error_type = log_parser._extract_error_type(raw_logs) or "DeploymentError"
    parsed_error = log_parser.ParsedError(
        platform=platform_enum,
        deployment_id=deployment_id,
        project_name=project,
        environment="staging",
        raw_log=raw_logs,
        error_type=error_type,
        error_message=log_parser._extract_error_message(raw_logs, error_type),
        stack_trace=log_parser._extract_stack_trace(raw_logs),
        affected_files=log_parser._extract_affected_files(raw_logs) or ["src/server.js"],
        exit_code=log_parser._extract_exit_code(raw_logs),
        build_phase=log_parser._extract_build_phase(raw_logs),
        ts_errors=log_parser._extract_ts_errors(raw_logs),
    )

    incident_store.record_received(
        deployment_id=deployment_id,
        platform=parsed_error.platform.value,
        project_name=parsed_error.project_name,
        environment=parsed_error.environment,
        error_type=parsed_error.error_type,
        error_message=parsed_error.error_message,
        stack_trace=parsed_error.stack_trace,
        affected_files=parsed_error.affected_files,
    )

    repo_structure = await github_client.get_repository_structure()
    file_contents = {}
    file_blob_shas = {}
    for f in parsed_error.affected_files:
        try:
            content, sha = await github_client.get_file_content_from_dev(f)
            file_contents[f] = content
            file_blob_shas[f] = sha
        except Exception as exc:
            logger.warning("Could not fetch %s from dev branch: %s", f, exc)

    incident_store.update_stage(deployment_id, "SOURCE_FETCHED")

    result = await agent.run_agent_pipeline(
        error=parsed_error,
        file_contents=file_contents,
        file_blob_shas=file_blob_shas,
        repo_structure=repo_structure,
    )
    patch = result.patch

    incident_store.update_stage(
        deployment_id,
        "REVIEWED",
        root_cause=patch.root_cause,
        steps=patch.steps,
        file_path=patch.file_path,
        original_snippet=patch.original_snippet,
        fixed_snippet=patch.fixed_snippet,
        explanation=patch.explanation,
        review_approved=result.review.approved,
        review_issues=result.review.issues,
        validation_checks=result.validation.to_dict()["checks"],
    )

    pr_body = _build_pr_body(parsed_error, patch, result.review)
    pr_url = await github_client.create_fix_branch_and_pr(
        file_path=patch.file_path,
        new_content=result.new_file_content,
        blob_sha=result.blob_sha,
        commit_msg=patch.commit_message,
        pr_title=patch.pr_title,
        pr_body=pr_body,
    )

    incident_store.update_stage(deployment_id, "PR_CREATED", pr_url=pr_url)

    report = {
        "platform": parsed_error.platform.value,
        "project_name": parsed_error.project_name,
        "environment": parsed_error.environment,
        "error_type": parsed_error.error_type,
        "error_message": parsed_error.error_message,
        "root_cause": patch.root_cause,
        "steps": patch.steps,
        "file_path": patch.file_path,
        "original_snippet": patch.original_snippet,
        "fixed_snippet": patch.fixed_snippet,
        "explanation": patch.explanation,
    }
    incident_store.update_stage(deployment_id, "NOTIFIED")
    return {"report": report, "pr_url": pr_url, "deployment_id": deployment_id}


