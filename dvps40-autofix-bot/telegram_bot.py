def build_app(token: str) -> Application:
    app = ApplicationBuilder().token(token).build()
    app.add_handler(CommandHandler("start", cmd_start))
    app.add_handler(CommandHandler("help", cmd_start))
    app.add_handler(CommandHandler("status", cmd_status))
    app.add_handler(CommandHandler("incidents", cmd_incidents))
    app.add_handler(CommandHandler("incident", cmd_incident_detail))
    app.add_handler(CommandHandler("simulate", cmd_simulate))
    app.add_handler(CommandHandler("fix", cmd_fix))
    app.add_handler(CallbackQueryHandler(handle_callback_query))
    return app


def main():
    token = get_token()
    if is_mock_token(token):
        logger.info("Mock Telegram Token detected. Running interactive pipeline self-test.")
        asyncio.run(run_interactive_cli())
    else:
        logger.info("Starting Telegram Polling Bot with live token...")
        app = build_app(token)
        app.run_polling()


if __name__ == "__main__":
    main()
