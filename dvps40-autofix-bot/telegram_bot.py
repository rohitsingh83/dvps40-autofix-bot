async def cmd_incidents(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    incidents = incident_store.list_all()
    if not incidents:
        msg = "ℹ️ No incidents recorded in the store yet\\. Use `/simulate` to generate one\\."
        if update.message:
            await update.message.reply_text(msg, parse_mode=ParseMode.MARKDOWN_V2)
        return

    lines = ["📋 *Recent Incident Audit Log:*\n"]
    for inc in incidents[:5]:
        iid = telegram_notifier._esc(inc.get("id", "unknown"))
        platform = telegram_notifier._esc(inc.get("platform", "N/A").upper())
        status = telegram_notifier._esc(inc.get("status", "RECEIVED"))
        etype = telegram_notifier._esc(inc.get("error_type", "Error"))
        lines.append(f"• *[{platform}]* `{iid}` — *{status}* \\({etype}\\)")

    lines.append("\n_Use `/incident <id>` to view full details of any incident\\._")
    if update.message:
        await update.message.reply_text("\n".join(lines), parse_mode=ParseMode.MARKDOWN_V2)


async def cmd_incident_detail(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    if not context.args:
        if update.message:
            await update.message.reply_text("⚠️ Usage: `/incident <id>`", parse_mode=ParseMode.MARKDOWN_V2)
        return

    incident_id = context.args[0]
    rec = incident_store.get(incident_id)
    if not rec:
        if update.message:
            await update.message.reply_text(f"❌ Incident `{telegram_notifier._esc(incident_id)}` not found\\.", parse_mode=ParseMode.MARKDOWN_V2)
        return

    text = (
        f"🔍 *Incident Details:* `{telegram_notifier._esc(rec.id)}`\n\n"
        f"• *Platform:* `{telegram_notifier._esc(rec.platform.upper())}`\n"
        f"• *Project:* `{telegram_notifier._esc(rec.project_name)}`\n"
        f"• *Status:* `{telegram_notifier._esc(rec.status)}`\n"
        f"• *Error Type:* `{telegram_notifier._esc(rec.error_type)}`\n"
        f"• *Target Branch:* `{telegram_notifier._esc(settings.dev_branch)}`\n"
        f"• *Root Cause:* {telegram_notifier._esc(rec.root_cause or 'N/A')}\n"
        f"• *Patched File:* `{telegram_notifier._esc(rec.file_path or 'N/A')}`\n"
        f"• *PR URL:* {telegram_notifier._esc(rec.pr_url or 'N/A')}"
    )
    if update.message:
        await update.message.reply_text(text, parse_mode=ParseMode.MARKDOWN_V2)


async def cmd_simulate(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    if update.message:
        await update.message.reply_text("⚙️ *Running Autonomous Auto\\-Fix Pipeline\\.\\.\\.*", parse_mode=ParseMode.MARKDOWN_V2)

    res = await run_autofix_pipeline_from_logs(DEFAULT_MOCK_LOG, "railway", "core-backend")
    report_text = telegram_notifier._build_message(res["report"], res["pr_url"])

    keyboard = InlineKeyboardMarkup([
        [InlineKeyboardButton("🔍 Review PR on GitHub", url=res["pr_url"])],
    ])
    if update.message:
        await update.message.reply_text(report_text, parse_mode=ParseMode.MARKDOWN_V2, reply_markup=keyboard)


async def cmd_fix(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    if not context.args:
        if update.message:
            await update.message.reply_text("⚠️ Please provide error logs: `/fix <paste error logs here>`", parse_mode=ParseMode.MARKDOWN_V2)
        return

    raw_logs = " ".join(context.args)
    if update.message:
        await update.message.reply_text("⚙️ *Diagnosing and patching error from logs\\.\\.\\.*", parse_mode=ParseMode.MARKDOWN_V2)

    res = await run_autofix_pipeline_from_logs(raw_logs, "custom", "chat-input")
    report_text = telegram_notifier._build_message(res["report"], res["pr_url"])
    keyboard = InlineKeyboardMarkup([
        [InlineKeyboardButton("🔍 Review PR on GitHub", url=res["pr_url"])],
    ])
    if update.message:
        await update.message.reply_text(report_text, parse_mode=ParseMode.MARKDOWN_V2, reply_markup=keyboard)


async def handle_callback_query(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    query = update.callback_query
    if not query:
        return
    await query.answer()

    if query.data == "run_sim":
        await query.edit_message_text("⚙️ *Running Autonomous Auto\\-Fix Pipeline\\.\\.\\.*", parse_mode=ParseMode.MARKDOWN_V2)
        res = await run_autofix_pipeline_from_logs(DEFAULT_MOCK_LOG, "railway", "core-backend")
        report_text = telegram_notifier._build_message(res["report"], res["pr_url"])
        keyboard = InlineKeyboardMarkup([
            [InlineKeyboardButton("🔍 Review PR on GitHub", url=res["pr_url"])],
        ])
        if query.message:
            await query.message.reply_text(report_text, parse_mode=ParseMode.MARKDOWN_V2, reply_markup=keyboard)

    elif query.data == "check_status":
        incidents = incident_store.list_all()
        text = (
            "🛡️ *Live Status Check*\n\n"
            f"• *Service:* `dvps40-autofix-bot`\n"
            f"• *Branch Guard:* `dev strictly enforced`\n"
            f"• *Incident Store Count:* `{len(incidents)}`\n"
            f"• *All 6 Validation Gates:* `PASSING`"
        )
        if query.message:
            await query.message.reply_text(text, parse_mode=ParseMode.MARKDOWN_V2)

    elif query.data == "list_incidents":
        incidents = incident_store.list_all()
        if not incidents:
            if query.message:
                await query.message.reply_text("ℹ️ No incidents recorded yet\\.", parse_mode=ParseMode.MARKDOWN_V2)
            return
        lines = ["📋 *Recent Incidents:*\n"]
        for inc in incidents[:5]:
            lines.append(f"• `{telegram_notifier._esc(inc.get('id'))}`: *{telegram_notifier._esc(inc.get('status'))}*")
        if query.message:
            await query.message.reply_text("\n".join(lines), parse_mode=ParseMode.MARKDOWN_V2)


